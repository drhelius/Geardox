#!/bin/bash

set -e

PYTHON=${PYTHON:-python3}

SCRIPT_DIR=$(cd "$(dirname "$0")" && pwd)

"$PYTHON" - "$SCRIPT_DIR" << 'PYTHON_EOF'
import hashlib
import io
import os
import sys
import zipfile

script_dir = sys.argv[1]

VERSION = "Enhanced DOSKEY 2.0a"
PACKAGE = "doskey20asrc.zip"
SHA256 = "a8c8aaddffa2c768130c140e38d784940af74476ec607a80768a0e084b150c2b"

def read_program():
    data = open(os.path.join(script_dir, PACKAGE), "rb").read()

    if hashlib.sha256(data).hexdigest() != SHA256:
        sys.exit("%s doesn't match its hash" % PACKAGE)

    with zipfile.ZipFile(io.BytesIO(data)) as archive:
        return archive.read("doskey.com")

def array(name, data):
    lines = ["const uint8_t %s[] =" % name, "{"]

    for i in range(0, len(data), 16):
        chunk = ", ".join("0x%02X" % b for b in data[i:i + 16])
        lines.append("    " + chunk + ("," if i + 16 < len(data) else ""))

    lines.append("};")
    lines.append("")
    lines.append("const uint32_t %s_size = %d;" % (name, len(data)))
    return "\n".join(lines)

header = """/*
 * ===========================================================================
 *  GENERATED FILE, DO NOT EDIT
 *
 *  Generated by platforms/shared/dependencies/doskey/build.sh from doskey20asrc.zip.
 *  To change it, update the package and its hash in build.sh, and run build.sh again.
 * ===========================================================================
 */

/*
 * Enhanced DOSKEY's program, written for Geardox
 * Enhanced DOSKEY: http://paulhoule.com/doskey, see COPYING and README.md
 */

#include "doskey.h"
"""

program = read_program()

with open(os.path.join(script_dir, "doskey.cpp"), "w") as out:
    out.write(header)
    out.write("\n" + array("k_doskey", program) + "\n")

print("Built %s: %d bytes" % (VERSION, len(program)))
PYTHON_EOF
